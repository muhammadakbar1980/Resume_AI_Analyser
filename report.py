"""
STEP 6 (part) - DOWNLOADABLE REPORT  (pure Python, no AI)

Builds a plain-text report from the scoring results and the advice.
This file is fully independent: it does not import any other project file.

Main function:
    build_report(results, advice) -> text
"""

from datetime import datetime


def _section(title, items, empty="None"):
    lines = ["", title, "-" * len(title)]
    if items:
        lines += [f"  - {item}" for item in items]
    else:
        lines.append(f"  {empty}")
    return lines


def build_report(results, advice=None):
    results = results or {}
    advice = advice or {}
    scores = results.get("section_scores", {})
    weights = results.get("weights", {})
    exp = results.get("experience", {})
    qual = results.get("qualification", {})

    lines = [
        "=" * 60,
        "RESUME ANALYSIS REPORT",
        "=" * 60,
        f"Date: {datetime.now().strftime('%d %B %Y, %H:%M')}",
    ]
    if results.get("candidate_name"):
        lines.append(f"Candidate: {results['candidate_name']}")
    if results.get("job_title"):
        lines.append(f"Job: {results['job_title']}")

    lines += [
        "",
        f"FINAL SCORE: {results.get('final_score', 0)}%",
        f"RESULT: {results.get('verdict', '')}",
        "",
        "Score breakdown",
        "---------------",
    ]
    for name in ("skills", "experience", "keywords", "qualification"):
        lines.append(f"  {name.title():<15} {scores.get(name, 0):>5}%   (weight {weights.get(name, 0)}%)")

    lines += [
        "",
        "Experience",
        "----------",
        f"  Candidate: {exp.get('candidate_years', 0):g} years | Required: {exp.get('required_years', 0):g} years",
        "",
        "Qualification",
        "-------------",
        f"  Candidate degree: {qual.get('candidate_degree', 'none')} | "
        f"Required: {qual.get('required_degree', 'none')} | "
        f"{'Meets requirement' if qual.get('degree_ok', True) else 'Below requirement'}",
    ]

    lines += _section("Matched required skills", results.get("matched_must_have"))
    lines += _section("MISSING required skills", results.get("missing_must_have"))
    lines += _section("Matched preferred skills", results.get("matched_nice_to_have"))
    lines += _section("Missing preferred skills", results.get("missing_nice_to_have"))
    lines += _section("ATS keywords found", results.get("keywords_found"))
    lines += _section("ATS keywords MISSING", results.get("keywords_missing"))
    lines += _section("Missing certifications", qual.get("certifications_missing"))
    lines += _section("ATS format issues", results.get("ats_format_issues"), "No format issues found")
    lines += _section("Problems", advice.get("problems"))
    lines += _section("Recommendations", advice.get("recommendations"))

    lines += ["", "Summary", "-------", "  " + advice.get("summary", ""), "", "=" * 60,
              "Generated by Resume Analyser. Scores are a guide, not a hiring decision."]
    return "\n".join(lines)
